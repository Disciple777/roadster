// Render api/config.php from .env.deploy and upload it to the server.
//
//   node tools/push-config.mjs           show what would be written (values masked)
//   node tools/push-config.mjs --yes     upload it
//
// The one operation that overwrites the live server config, so it is its own explicit command.
// The rendered file goes to the OS temp directory (never the project, so a local api/config.php
// can never exist) and is deleted right after the upload.
//
// Needs DB_NAME, DB_USER, DB_PASSWORD in .env.deploy (optional: DB_HOST, DB_PORT, DB_PREFIX).

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { loadEnv, safeError, connect } from './env.mjs';

const GO = process.argv.includes('--yes');
const q = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'"); // PHP single-quoted literal

const render = (env) => `<?php
// Roadster Thruster server config. GENERATED by tools/push-config.mjs from .env.deploy: edit that and re-run.
return [
    'db_host' => '${q(env.DB_HOST || 'localhost')}',
    'db_name' => '${q(env.DB_NAME)}',
    'db_user' => '${q(env.DB_USER)}',
    'db_pass' => '${q(env.DB_PASSWORD)}',
    'db_port' => ${Number(env.DB_PORT) || 3306},
    'prefix'  => '${q(env.DB_PREFIX || 'rdstr_')}',
];
`;

async function main() {
  let env;
  try { env = loadEnv(); } catch (e) { console.error(e.message); process.exitCode = 1; return; }
  const missing = ['DB_NAME', 'DB_USER', 'DB_PASSWORD'].filter((k) => !env[k]);
  if (missing.length) { console.error('.env.deploy is missing: ' + missing.join(', ')); process.exitCode = 1; return; }

  const body = render(env);
  console.log('api/config.php to write:');
  console.log('  db_host  ' + (env.DB_HOST || 'localhost'));
  for (const k of ['DB_NAME', 'DB_USER', 'DB_PASSWORD']) console.log(`  ${k.padEnd(11)} [set, ${env[k].length} chars]`);
  console.log('  prefix   ' + (env.DB_PREFIX || 'rdstr_'));
  if (!GO) { console.log('\nDry run. Re-run with --yes to upload (overwrites the live config).'); return; }

  const tmp = path.join(os.tmpdir(), `rdstr-config-${process.pid}.php`);
  fs.writeFileSync(tmp, body, { mode: 0o600 });
  let client;
  try {
    client = await connect(env);
    const dir = env.FTP_REMOTE_ROOT.replace(/\/+$/, '') + '/api';
    await client.ensureDir(dir);
    await client.uploadFrom(tmp, 'config.php');
    const found = (await client.list(dir)).find((f) => f.name === 'config.php');
    console.log(found ? `  uploaded api/config.php (${found.size} B)` : '  WARNING: config.php not in the remote listing after upload');
  } catch (err) {
    console.error('  FAILED: ' + safeError(err, env));
    process.exitCode = 1;
  } finally {
    if (client) client.close();
    try { fs.unlinkSync(tmp); } catch { /* already gone */ }
  }
}

main();
